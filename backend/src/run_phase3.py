"""Run Phase 3 harmonization and write the harmonization report."""

from __future__ import annotations

import logging

import pandas as pd

from config import HARMONIZED_DIR, REPORTS_DIR
from harmonize import GRID_SIZE_DEG, HarmonizationResult, run_harmonization

logger = logging.getLogger(__name__)


def _md_table(frame: pd.DataFrame) -> str:
    header = "| " + " | ".join(str(c) for c in frame.columns) + " |"
    divider = "| " + " | ".join("---" for _ in frame.columns) + " |"
    body = ["| " + " | ".join(str(v) for v in row) + " |" for row in frame.itertuples(index=False)]
    return "\n".join([header, divider, *body])


def render_report(result: HarmonizationResult) -> str:
    h = result.harmonized
    presence = result.cell_day_presence
    coverage = result.coverage_calendar
    year = h["acquisition_date"].str[:4]

    by_sensor = (
        h.assign(year=year)
        .groupby(["sensor_key", "year"])
        .agg(
            rows=("record_id", "size"),
            static_sources=("is_static_source", "sum"),
            vegetation_fire_candidates=("is_vegetation_fire_candidate", "sum"),
            water_detections=("is_water_detection", "sum"),
        )
        .reset_index()
    )
    by_sensor["static_share_pct"] = (100 * by_sensor["static_sources"] / by_sensor["rows"]).round(1)

    cov_summary = (
        coverage.groupby(["sensor_key", "coverage_status"]).size().unstack(fill_value=0).reset_index()
    )

    lines = [
        "# FireScope Phase 3 - Sensor Harmonization Report",
        "",
        "This report is generated by `src/run_phase3.py` from the files on disk.",
        "",
        "## Result",
        "",
        f"- Harmonized rows: **{len(h):,}**",
        f"- Cell-day presence rows (grid {GRID_SIZE_DEG} deg): **{len(presence):,}**",
        f"- Exact duplicates flagged within a sensor: **{int(h['is_exact_duplicate_within_sensor'].sum()):,}** (flagged, not removed)",
        f"- Records without a valid UTC time: **{int(h['acquisition_datetime_utc'].isna().sum()):,}**",
        "- No record was dropped, added, or merged. Each input row maps to one output row.",
        "",
        "## Inputs",
        "",
        _md_table(result.input_summary),
        "",
        "NOAA-20 2023 uses the full-year file (31,025 rows) instead of the January-only file (2,093 rows).",
        "The old file was not overwritten. Its January rows match the new file after numeric normalization.",
        "",
        "## Records by sensor, year, and hotspot type",
        "",
        _md_table(by_sensor),
        "",
        "Raw counts above are per-sensor and must not be summed as independent fires.",
        "MODIS (about 1 km) and VIIRS (about 375 m) detect at different resolutions.",
        "",
        "## Coverage calendar (sensor x day, 2023-2025)",
        "",
        _md_table(cov_summary),
        "",
        "`no_records_unconfirmed` and `documented_source_gap` describe missing records only.",
        "They do not mean that no thermal activity occurred.",
        "",
        "## Confidence handling",
        "",
        "- MODIS: `confidence_numeric` (0-100). `confidence_class` is empty.",
        "- VIIRS: `confidence_class` (l, n, h). `confidence_numeric` is empty.",
        "- No unified confidence score was created.",
        "",
        "## Output files",
        "",
        f"- `{(HARMONIZED_DIR / 'firescope_harmonized.csv').name}`: one row per detection, common schema.",
        f"- `{(HARMONIZED_DIR / 'cell_day_presence.csv').name}`: cross-sensor cells with at least one detection per day.",
        f"- `{(HARMONIZED_DIR / 'coverage_calendar.csv').name}`: per sensor and day coverage status.",
        f"- `{(HARMONIZED_DIR / 'harmonization_inputs.csv').name}`: inputs used and hash checks.",
    ]
    return "\n".join(lines) + "\n"


def run_phase3() -> HarmonizationResult:
    result = run_harmonization(write=True)
    REPORTS_DIR.mkdir(parents=True, exist_ok=True)
    (REPORTS_DIR / "phase3_harmonization_report.md").write_text(
        render_report(result), encoding="utf-8"
    )
    return result
